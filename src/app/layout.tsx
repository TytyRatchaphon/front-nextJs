import { fetchWebsiteSettings } from "@/services/apiServices";

export async function generateMetadata(): Promise<Metadata> {
  const settingsResponse = await fetchWebsiteSettings();
  const settings = settingsResponse?.data;

  return {
    title: settings?.seo_title || "Enjoybook",
    description: settings?.seo_description || "Generated by create next app",
    keywords: settings?.seo_keyword || "นิยาย, อ่านนิยาย",
  };
}

